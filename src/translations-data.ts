export function getTranslation(key: TranslationKey, lang: string): string {
  const entry = translations[key];
  if (!entry) return key;
  if (lang in entry) return entry[lang];
  if (lang.startsWith("es-") && entry["es-419"]) return entry["es-419"];
  if (lang.startsWith("pt-") && entry["pt-BR"]) return entry["pt-BR"];
  if (lang.startsWith("zh-") && entry["zh-Hans"]) return entry["zh-Hans"];
  if (lang.startsWith("en-") && entry["en"]) return entry["en"];
  if (entry["en"]) return entry["en"];
  return key;
}